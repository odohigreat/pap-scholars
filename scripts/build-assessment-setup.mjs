import { readFile, writeFile } from 'node:fs/promises';

const files = ['202610150001_course_assessments.sql', '202610150002_assessment_review_workflow.sql'];
const sections = [];
for (const file of files) {
  const sql = await readFile(new URL(`../supabase/migrations/${file}`, import.meta.url), 'utf8');
  // Use one transaction so either the complete assessment setup succeeds or nothing changes.
  sections.push(`-- Source: ${file}\n${sql.replace(/^begin;\s*$/m, '').replace(/^commit;\s*$/m, '').trim()}`);
}
const header = `-- PAP Scholars assessment setup: paste this ENTIRE file into Supabase SQL Editor and Run.
-- Creates the assessment tables first, then installs the 20-question review workflow.
-- Safe to rerun: preserves student results and published assessments.
-- Generated by: node scripts/build-assessment-setup.mjs
begin;
do $prerequisites$ begin
  if to_regclass('public.courses') is null or to_regclass('public.enrollments') is null
    or to_regclass('public.lessons') is null or to_regclass('public.course_modules') is null
    or to_regclass('public.lesson_progress') is null then
    raise exception 'Base course tables are missing. Apply the initial schema, enrollment tracking, and catalogue migrations first.';
  end if;
end $prerequisites$;
`;
await writeFile(new URL('../supabase/setup-course-assessments.sql', import.meta.url), `${header}\n${sections.join('\n\n')}\n\ncommit;\n`);
console.log('Created supabase/setup-course-assessments.sql. Run the entire file in Supabase SQL Editor.');
